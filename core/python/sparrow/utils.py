import torch
import random
import numpy as np


def set_seed(seed=42):
    """
    Set all relevant random seeds for reproducible training across Python,
    NumPy, and PyTorch (CPU and GPU).

    Args:
        seed (int, optional): Random seed to use. Default is 42.
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
    torch.use_deterministic_algorithms(True, warn_only=True)
